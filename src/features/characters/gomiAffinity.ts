export const GOMI_AFFECTION_THRESHOLDS = [0, 20, 30, 60, 90] as const;
export type GomiAffinity = 0 | 1 | 2 | 3 | 4;
export function gomiAffinity(affection: number): GomiAffinity {
  return affection >= 90 ? 4 : affection >= 60 ? 3 : affection >= 30 ? 2 : affection >= 20 ? 1 : 0;
}
