function gomiTopic(id: string) {
  if (/^(delete(?:-|$)|exclude(?:-|$)|reset-people$|clear-library$)/.test(id)) return 'destructive';
  if (/select|choice|deselect/.test(id)) return 'selection';
  if (/save|assign|register|name|title|body|mood/.test(id)) return 'write';
  if (/analysis|detect|review|candidate|face|pet-view|refresh-pet|resume/.test(id)) return 'analysis';
  if (/memory|trip|timeline|region|map|rediscover/.test(id)) return 'memory';
  if (/close|cancel|back|list/.test(id)) return 'navigation';
  if (/photo|album|zoom|next|prev|export|media/.test(id)) return 'browse';
  return undefined;
}

export function resolveHelpDialogue(definition: CharacterDefinition, affection: number, instruction: string,
  options: { stepId?: string; variation?: number; previousLine?: string } = {}) {
  const tier = gomiAffinity(affection);
  const base = voices[definition.type]?.[tier] ?? definition.personality?.speechTone ?? '차근차근 살펴볼게요.';
  const topic = definition.type === 'gomi' ? gomiTopic(options.stepId ?? '') : undefined;
  const pool = [...new Set([base, ...(alternatives[definition.type]?.[tier] ?? []), ...(topic ? [gomiTopics[topic][tier]] : [])])];
  let hash = 0;
  for(const letter of options.stepId ?? '')hash=(hash*31+letter.charCodeAt(0))>>>0;
  const variation=Number.isFinite(options.variation)?Math.max(0,Math.floor(options.variation!)):0;
  let index=(hash+variation)%pool.length;
  if(pool.length>1 && pool[index]===options.previousLine)index=(index+1)%pool.length;
  return { tier, line: pool[index], instruction };
}
