import {test,expect} from '@playwright/test';
import {writeFileSync,mkdirSync} from 'node:fs';
import {installOwnAi,configureInference,requestedInputs} from './fixtures/own-ai';
for(const width of [320,360,393]) test(`Gomi snack failure at ${width}px`,async({page})=>{
 const before=process.env.STAGE==='before', dir=process.env.PROOF_DIR!;
 mkdirSync(dir,{recursive:true});
 await page.setViewportSize({width,height:780});
 await installOwnAi(page,{affection:95,worker:{error:'AI_OWN_NO_VALID_LINE'}});
 await page.goto('/');
 await page.getByRole('button',{name:'함께하기',exact:true}).click();
 await page.getByRole('button',{name:'간식 주기',exact:true}).click();
 const message=page.locator('#homeMessage');
 await expect(message).toHaveAttribute('data-state','failed');
 await page.evaluate(()=>document.fonts.ready);
 await message.evaluate(node=>node.scrollIntoView({block:'center',behavior:'instant'}));
 await page.screenshot({path:`${dir}/${process.env.STAGE}-${width}.png`});
 const text=await message.innerText(),retry=page.getByRole('button',{name:'대사 다시 생성',exact:true});
 await expect(retry).toHaveCount(before?0:1);
 const measure=()=>page.evaluate(()=>({care:localStorage.getItem('gamjassak:companion:v1:gomi'),writes:(window as any).ownAiProbe.saveStarted,overflow:document.documentElement.scrollWidth>innerWidth}));
 const initial=await measure();
 await configureInference(page,{error:null});
 await (before?page.locator('.homeMascot'):retry).click();
 await expect(message).toHaveAttribute('data-source','on-device');
 const end=await measure(),actions=(await requestedInputs(page)).map((r:any)=>r.action);
 expect(actions).toEqual(['treat',before?'touch':'treat']);
 expect(end.writes-initial.writes).toBe(before?1:0);
 expect(end.care).toBe(initial.care);
 expect(end.overflow).toBe(false);
 writeFileSync(`${dir}/${process.env.STAGE}-${width}.json`,JSON.stringify({text,actions,additionalRelationshipSaves:end.writes-initial.writes,overflow:end.overflow}));
});