import { expect, test } from '@playwright/test';
import { auditLibrary } from './audit-fixture';
import { mkdir, writeFile } from 'node:fs/promises';

test('capture current app tasks and record expectations before actions', async ({page}, info) => {
  test.skip(info.project.name !== 'mobile', 'Android-sized audit capture.');
  const stage=process.env.APP_UX_STAGE || 'before', folder=`preview-results/app-ux/${stage}`;
  await mkdir(folder,{recursive:true});
  const notes:unknown[]=[];
  async function shot(step:string, expectation:string) {
    await page.evaluate(async()=>{
      await document.fonts.ready;
      await Promise.all([...document.images].filter(img=>{const r=img.getBoundingClientRect();return r.bottom>0&&r.top<innerHeight;}).map(img=>{img.loading='eager';return img.decode().catch(()=>{});}));
      await new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)));
    });
    await page.screenshot({path:`${folder}/${step}.png`,fullPage:false,animations:'disabled'});
    const buttons=await page.getByRole('button').evaluateAll(nodes=>nodes.filter(n=>n.getBoundingClientRect().height>0).map(n=>({name:n.getAttribute('aria-label')||n.getAttribute('title')||n.textContent?.trim(),disabled:(n as HTMLButtonElement).disabled})));
    notes.push({step,expectation,buttons});
  }
  await auditLibrary(page);await page.emulateMedia({reducedMotion:'reduce'});
  await shot('01-home','처음 보는 메뉴에서도 사진·일기·인물 화면을 찾을 수 있다.');
  await page.locator('.navList').getByRole('button',{name:'사진 기록',exact:true}).click();
  await shot('02-photos','선택 버튼으로 여러 사진을 고르고 선택 개수와 취소를 확인한다.');
  await page.getByRole('button',{name:/^(사진 선택|선택)$/,exact:true}).click();
  await page.locator('.mediaTile').first().click();
  await shot('03-photo-selection','선택 후 작업을 화면 아래에서 찾고 원본 삭제와 등록 해제를 구분한다.');
  const beforeBack=await page.locator('.selectionDock').innerText();
  await page.evaluate(()=>window.__gamjassakBack?.());
  notes.push({step:'04-photo-back',expected:'사진 목록에 머물고 선택 모드만 종료한다.',beforeBack,actual:{home:await page.locator('.homeView').count(),photoPanel:await page.locator('.libraryView').count(),selection:await page.locator('.selectionDock').count()}});
  await shot('04-photo-back','Android 뒤로는 선택 모드를 먼저 종료한다.');
  await page.locator('.navList').getByRole('button',{name:'사진 기록',exact:true}).click();
  const cancel=page.getByRole('button',{name:/^(선택 끝내기|선택 취소)$/,exact:true});if(await cancel.count())await cancel.first().click();
  await page.locator('.mediaTile').first().click();
  await shot('05-favorite','하트가 현재 즐겨찾기 상태와 추가·해제를 명확하게 보여준다.');
  await page.getByTitle('닫기',{exact:true}).click();
  await page.locator('.navList').getByRole('button',{name:'내 앨범',exact:true}).click();
  await page.getByRole('button',{name:'선택',exact:true}).click();
  await page.locator('.savedAlbumOpen').first().click();
  await shot('06-album-selection','선택한 앨범 수와 전체 선택·취소·앨범 삭제 범위를 확인한다.');
  await page.locator('.navList').getByRole('button',{name:'일기장',exact:true}).click();
  await shot('07-diary','일기 쓰기를 바로 찾고 카드 메뉴를 버튼 옆에서 연다.');
  await page.getByRole('button',{name:'가을 산책 일기 메뉴',exact:true}).click();
  await shot('08-diary-menu','더보기 메뉴가 누른 버튼 옆에서 열리고 일기 수정을 선택한다.');
  await page.getByRole('button',{name:'일기 수정',exact:true}).click();
  await page.getByLabel('일기 사진 파일').setInputFiles('tests/fixtures/pet-dog.jpg');
  await shot('09-diary-editor','사진 삭제는 원본 삭제인지 첨부 해제인지 분명해야 한다.');
  page.once('dialog',dialog=>dialog.accept());
  await page.getByRole('button',{name:'닫기',exact:true}).click();
  await page.getByRole('button',{name:/^(일기 선택|선택)$/,exact:true}).click();
  await page.locator('.diaryOpen').first().click();
  await shot('10-diary-selection','일기 선택도 사진 선택과 같은 취소·선택 개수·하단 작업을 제공한다.');
  await page.evaluate(()=>window.__gamjassakBack?.());
  notes.push({step:'11-diary-back',expected:'일기 목록에 머물고 선택 모드만 종료한다.',actual:{diary:await page.locator('.diaryView').count(),selection:await page.locator('.diaryBulk').count()}});
  await shot('11-diary-back','뒤로 가기는 일기 목록을 유지하며 선택을 취소한다.');
  await page.locator('.navList').getByRole('button',{name:'사람과 반려동물',exact:true}).click();
  await page.getByRole('button',{name:'가족 24장',exact:true}).click();
  await shot('12-person-detail','인물 상세에서 사진 선택·이름 변경·사진 연결을 찾는다.');
  await page.getByRole('button',{name:'선택',exact:true}).click();
  await page.evaluate(()=>window.__gamjassakBack?.());
  notes.push({step:'13-person-back',expected:'인물 상세에서 선택만 취소한다.',actual:{people:await page.locator('.peopleView').count(),selection:await page.locator('.entitySelectionBar').count()}});
  await shot('13-person-back','뒤로 가기는 인물 상세를 유지하며 선택을 취소한다.');
  await page.locator('.navList').getByRole('button',{name:'사람과 반려동물',exact:true}).click();
  await page.getByRole('tab',{name:'반려동물',exact:true}).click();
  await page.getByRole('button',{name:'보리 1장',exact:true}).click();
  await shot('14-pet-detail','인물 상세와 같은 위치에서 같은 기능을 조작한다.');
  await page.getByRole('button',{name:'감자싹 홈으로 이동',exact:true}).click();
  await page.locator('.homeShortcuts').scrollIntoViewIfNeeded();
  await shot('15-home-shortcuts','홈의 일기장 다음에 사람과 반려동물 바로가기가 보인다.');
  await page.locator('.navList').getByRole('button',{name:'사람과 반려동물',exact:true}).click();
  await page.getByRole('tab',{name:'인물',exact:true}).click();
  await page.getByRole('button',{name:stage==='before'?/^(고미|사용 방법) 도움말 열기$/:'현재 화면 도움말',exact:true}).click();
  if(stage!=='before') await expect(page.getByRole('dialog',{name:'버튼 도움말',exact:true})).toBeVisible();
  await shot('16-people-help','인물 도움말에서는 인물 기능만 확인한다.');
  await page.getByRole('button',{name:stage==='before'?'도움말 닫기':'도움말 종료',exact:true}).click();
  await page.getByRole('tab',{name:'반려동물',exact:true}).click();
  await page.getByRole('button',{name:stage==='before'?/^(고미|사용 방법) 도움말 열기$/:'현재 화면 도움말',exact:true}).click();
  if(stage!=='before') await expect(page.getByRole('dialog',{name:'버튼 도움말',exact:true})).toBeVisible();
  if(stage!=='before') await page.getByRole('dialog',{name:'버튼 도움말',exact:true}).getByRole('button',{name:'다음',exact:true}).click();
  await shot('17-pet-help','반려동물 도움말에서는 반려동물 기능만 확인한다.');
  await page.getByRole('button',{name:stage==='before'?'도움말 닫기':'도움말 종료',exact:true}).click();
  await writeFile(`${folder}/observations.json`,JSON.stringify(notes,null,2));
});

